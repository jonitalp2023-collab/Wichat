-- Ejecutar en Supabase > SQL Editor.
-- Si ya existe public.messages con otras columnas, revisá el esquema antes de ejecutar.
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 2 and 24),
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);
alter table public.messages enable row level security;
drop policy if exists "messages_read_public" on public.messages;
create policy "messages_read_public" on public.messages
for select to anon, authenticated using (true);
drop policy if exists "messages_insert_public" on public.messages;
create policy "messages_insert_public" on public.messages
for insert to anon, authenticated with check (
  char_length(nickname) between 2 and 24 and char_length(body) between 1 and 1000
);
do $$
begin
  alter publication supabase_realtime add table public.messages;
exception when duplicate_object then null;
when undefined_object then null;
end $$;
