begin;

alter table public.chat_profiles
  add column if not exists bio text,
  add column if not exists avatar_url text,
  add column if not exists status text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname='chat_profiles_bio_length_check' and conrelid='public.chat_profiles'::regclass) then
    alter table public.chat_profiles add constraint chat_profiles_bio_length_check check (bio is null or char_length(bio)<=160);
  end if;
  if not exists (select 1 from pg_constraint where conname='chat_profiles_status_length_check' and conrelid='public.chat_profiles'::regclass) then
    alter table public.chat_profiles add constraint chat_profiles_status_length_check check (status is null or char_length(status)<=40);
  end if;
  if not exists (select 1 from pg_constraint where conname='chat_profiles_avatar_https_check' and conrelid='public.chat_profiles'::regclass) then
    alter table public.chat_profiles add constraint chat_profiles_avatar_https_check check (avatar_url is null or (char_length(avatar_url)<=2048 and avatar_url ~* '^https://'));
  end if;
end $$;

alter table public.messages add column if not exists message_type text not null default 'text', add column if not exists media_url text;
alter table public.private_messages add column if not exists message_type text not null default 'text', add column if not exists media_url text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname='messages_media_type_check' and conrelid='public.messages'::regclass) then
    alter table public.messages add constraint messages_media_type_check check (message_type in ('text','sticker','gif'));
  end if;
  if not exists (select 1 from pg_constraint where conname='messages_media_url_check' and conrelid='public.messages'::regclass) then
    alter table public.messages add constraint messages_media_url_check check ((message_type='text' and media_url is null) or (message_type in ('sticker','gif') and media_url is not null and char_length(media_url)<=2048 and media_url ~* '^https://'));
  end if;
  if not exists (select 1 from pg_constraint where conname='private_messages_media_type_check' and conrelid='public.private_messages'::regclass) then
    alter table public.private_messages add constraint private_messages_media_type_check check (message_type in ('text','sticker','gif'));
  end if;
  if not exists (select 1 from pg_constraint where conname='private_messages_media_url_check' and conrelid='public.private_messages'::regclass) then
    alter table public.private_messages add constraint private_messages_media_url_check check ((message_type='text' and media_url is null) or (message_type in ('sticker','gif') and media_url is not null and char_length(media_url)<=2048 and media_url ~* '^https://'));
  end if;
end $$;

create table if not exists public.chat_message_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint references public.messages(id) on delete cascade,
  private_message_id bigint references public.private_messages(id) on delete cascade,
  user_id uuid not null,
  reaction text not null,
  created_at timestamptz not null default now(),
  constraint chat_message_reactions_one_target check ((message_id is not null and private_message_id is null) or (message_id is null and private_message_id is not null)),
  constraint chat_message_reactions_allowed check (reaction in ('👍','❤️','😂','😮','😢','👏','🔥'))
);

create unique index if not exists chat_reactions_public_unique on public.chat_message_reactions(message_id,user_id,reaction) where message_id is not null;
create unique index if not exists chat_reactions_private_unique on public.chat_message_reactions(private_message_id,user_id,reaction) where private_message_id is not null;
create index if not exists chat_reactions_public_message_idx on public.chat_message_reactions(message_id) where message_id is not null;
create index if not exists chat_reactions_private_message_idx on public.chat_message_reactions(private_message_id) where private_message_id is not null;

alter table public.chat_message_reactions enable row level security;
revoke all on public.chat_message_reactions from anon, authenticated;
grant select,insert,delete on public.chat_message_reactions to authenticated;
grant usage,select on sequence public.chat_message_reactions_id_seq to authenticated;

drop policy if exists chat_reactions_read on public.chat_message_reactions;
create policy chat_reactions_read on public.chat_message_reactions for select to authenticated using (
  auth.uid() is not null and (message_id is not null or (private_message_id is not null and exists (
    select 1 from public.private_messages pm where pm.id=private_message_id and (pm.sender_id=auth.uid() or pm.recipient_id=auth.uid())
  )))
);

drop policy if exists chat_reactions_insert_own on public.chat_message_reactions;
create policy chat_reactions_insert_own on public.chat_message_reactions for insert to authenticated with check (
  auth.uid() is not null and user_id=auth.uid() and (message_id is not null or (private_message_id is not null and exists (
    select 1 from public.private_messages pm where pm.id=private_message_id and (pm.sender_id=auth.uid() or pm.recipient_id=auth.uid())
  )))
);

drop policy if exists chat_reactions_delete_own on public.chat_message_reactions;
create policy chat_reactions_delete_own on public.chat_message_reactions for delete to authenticated using (auth.uid() is not null and user_id=auth.uid());

create table if not exists public.chat_points_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  points_delta integer not null check (points_delta between 1 and 1000),
  reason text not null check (char_length(reason) between 1 and 120),
  event_key text not null unique,
  created_at timestamptz not null default now()
);
create index if not exists chat_points_ledger_user_created_idx on public.chat_points_ledger(user_id,created_at desc);

alter table public.chat_points_ledger enable row level security;
revoke all on public.chat_points_ledger from anon,authenticated;
grant select on public.chat_points_ledger to authenticated;
drop policy if exists chat_points_read_authenticated on public.chat_points_ledger;
create policy chat_points_read_authenticated on public.chat_points_ledger for select to authenticated using (auth.uid() is not null);

commit;
